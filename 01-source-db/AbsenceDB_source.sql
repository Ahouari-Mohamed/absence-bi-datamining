GO
UPDATE da
SET    da.taux_absenteisme = t.total_jours * 100.0 / 20
FROM   Detail_Absence da
JOIN  (SELECT d.code_employee, SUM(d.nb_jour) AS total_jours
       FROM Detail_Absence d
       JOIN Demande_Absence a ON a.num_demande = d.num_demande
       WHERE a.status_ = N'Approuvée'
       GROUP BY d.code_employee) t
  ON  t.code_employee = da.code_employee;
