USE master;
GO
IF DB_ID('AbsenceDB') IS NOT NULL
BEGIN
    ALTER DATABASE AbsenceDB SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE AbsenceDB;
END
GO
CREATE DATABASE AbsenceDB;
GO
USE AbsenceDB;
GO

CREATE TABLE Ville (
    id_ville  INT           NOT NULL PRIMARY KEY,
    nom       NVARCHAR(100) NOT NULL,
    region    NVARCHAR(100) NOT NULL,
    pays      NVARCHAR(100) NOT NULL
);

CREATE TABLE Employee (
    code_emp  INT           NOT NULL PRIMARY KEY,
    nom       NVARCHAR(100) NOT NULL,
    prenom    NVARCHAR(100) NOT NULL,
    service   NVARCHAR(100) NOT NULL,
    id_ville  INT           NOT NULL,
    CONSTRAINT FK_Employee_Ville FOREIGN KEY (id_ville) REFERENCES Ville(id_ville)
);

CREATE TABLE Categorie (
    id_categorie INT           NOT NULL PRIMARY KEY,
    nom_cat      NVARCHAR(100) NOT NULL,
    description_ NVARCHAR(255) NULL
);

CREATE TABLE Demande_Absence (
    num_demande   INT           NOT NULL PRIMARY KEY,
    date_demande  DATE          NOT NULL,
    date_debut    DATE          NOT NULL,
    date_fin      DATE          NOT NULL,
    status_       NVARCHAR(50)  NOT NULL,
    id_categorie  INT           NOT NULL,
    CONSTRAINT FK_Demande_Categorie FOREIGN KEY (id_categorie) REFERENCES Categorie(id_categorie),
    CONSTRAINT CK_Demande_Dates CHECK (date_fin >= date_debut)
);

CREATE TABLE Detail_Absence (
    num_demande       INT   NOT NULL PRIMARY KEY,
    code_employee     INT   NOT NULL,
    nb_jour           INT   NOT NULL,           -- jours d'absence de la demande
    taux_absenteisme  FLOAT NULL,               -- taux de l'employe (voir UPDATE en fin de script)
    CONSTRAINT FK_Detail_Demande  FOREIGN KEY (num_demande)   REFERENCES Demande_Absence(num_demande),
    CONSTRAINT FK_Detail_Employee FOREIGN KEY (code_employee) REFERENCES Employee(code_emp)
);
GO

